#!/usr/bin/env bash
# @file changelog_archive.sh
# @brief Move old releases out of CHANGELOG.md into per-major archive files
# @description
#   `CHANGELOG.md` only ever grows, and every release, review and agent that
#   reads it pays for the whole history. This script moves every released
#   section older than a cut-off version into `docs/changelog/CHANGELOG-<major>.x.md`,
#   one file per major version, together with the link references those
#   sections use, and leaves an index of the archive files in the preamble of
#   `CHANGELOG.md`.
#
#   The split is idempotent: a second run with the same cut-off changes
#   nothing, and a later run with a higher cut-off adds the newly archived
#   versions to the right files, merged in version order. When a version is
#   found both in `CHANGELOG.md` and in an archive, the copy in `CHANGELOG.md`
#   wins, since that is the one a contributor edits. `## [Unreleased]` is never
#   moved, whatever the cut-off.
#
#   Each archive keeps the Keep a Changelog layout, minus `Unreleased`, so
#   `scripts/lint.sh --stage changelog` checks it with the same rules as the
#   main file. `scripts/release.sh` only rewrites `Unreleased` and its link,
#   so it is unaffected by where older sections live.
#
# @example
#   scripts/changelog_archive.sh --before 6.0.0 --dry-run  # list what would move
#   scripts/changelog_archive.sh --before 6.0.0            # move 5.x and older
#
# @see
#   - `scripts/lint.sh`
#   - `docs/MIGRATING.md`
SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
# shellcheck source=init.sh
. "${SCRIPT_DIR}/../init.sh" --modules "cli semver"

dybatpho::register_common_handlers

# The markers around the generated index in the preamble of `CHANGELOG.md`.
# `scripts/lint.sh` looks for the same strings.
ARCHIVE_BEGIN="<!-- changelog-archive: generated by scripts/changelog_archive.sh -->"
ARCHIVE_END="<!-- /changelog-archive -->"

# @description Validator for `--before`: a plain `major.minor.patch` version,
#   which is the only shape a release heading may have.
# @arg $1 string Value to check
# @exitcode 0 The value is a release version
# @exitcode 1 Otherwise
# @internal
function __dybatpho_changelog_is_release {
  local value
  dybatpho::expect_args value -- "$@"
  [[ "${value}" =~ ^[0-9]+\.[0-9]+\.[0-9]+$ ]]
}

# @description Split a changelog into one file per released section and one
#   per link reference, so sections can be merged and reordered by version.
#   A section runs from its `## [x.y.z]` heading to the next heading or to the
#   first link reference, without the blank lines that pad its end.
# @arg $1 path Changelog or archive file to read
# @arg $2 path Directory receiving `section/<version>` and `ref/<version>`
# @arg $3 string Space-separated versions to extract, or `*` for every version
# @internal
function __dybatpho_changelog_extract {
  local _file _out _versions
  dybatpho::expect_args _file _out _versions -- "$@"
  mkdir -p "${_out}/section" "${_out}/ref"
  awk -v out="${_out}" -v wanted=" ${_versions} " '
    function want(v) { return wanted == " * " || index(wanted, " " v " ") }
    function flush(   i) {
      if (current == "") return
      while (count > 0 && lines[count] ~ /^[[:space:]]*$/) count--
      path = out "/section/" current
      printf "" > path
      for (i = 1; i <= count; i++) print lines[i] > path
      close(path)
      current = ""; count = 0
    }
    /^## \[/ {
      flush()
      version = $0
      sub(/^## \[/, "", version); sub(/\].*$/, "", version)
      if (version ~ /^[0-9]+\.[0-9]+\.[0-9]+$/ && want(version)) {
        current = version; lines[++count] = $0
      }
      next
    }
    /^\[[^]]+\]: / {
      flush()
      version = $0
      sub(/^\[/, "", version); sub(/\]: .*$/, "", version)
      if (version ~ /^[0-9]+\.[0-9]+\.[0-9]+$/ && want(version)) {
        path = out "/ref/" version
        print > path
        close(path)
      }
      next
    }
    current != "" { lines[++count] = $0 }
    END { flush() }
  ' "${_file}"
}

# @description Print the released versions a changelog has a heading for, in
#   file order.
# @arg $1 path Changelog to read
# @stdout One version per line
# @internal
function __dybatpho_changelog_versions {
  local file
  dybatpho::expect_args file -- "$@"
  sed -n 's/^## \[\([0-9][0-9]*\.[0-9][0-9]*\.[0-9][0-9]*\)\].*/\1/p' "${file}"
}

# @description Write one archive file from the sections and references in a
#   work directory, newest version first.
# @arg $1 path Archive file to write
# @arg $2 string Major version the archive holds
# @arg $3 path Work directory holding `section/` and `ref/`
# @arg $4 string Link from the archive back to the main changelog
# @internal
function __dybatpho_changelog_render_archive {
  local _archive _major _work _back
  dybatpho::expect_args _archive _major _work _back -- "$@"
  local -a versions=()
  local version listing
  # Every section of this archive is named `<major>.<minor>.<patch>`.
  listing="$(cd "${_work}/section" && printf '%s\n' "${_major}".*)"
  listing="$(printf '%s\n' "${listing}" | sort -t. -k1,1nr -k2,2nr -k3,3nr)"
  while IFS= read -r version || [[ -n "${version}" ]]; do
    [[ -n "${version}" ]] && versions+=("${version}")
  done <<< "${listing}"

  {
    printf '# Changelog: %s.x releases\n\n' "${_major}"
    printf 'Releases %s.x of dybatpho, archived from [CHANGELOG.md](%s) by\n' "${_major}" "${_back}"
    cat << 'EOF'
`scripts/changelog_archive.sh`. The format is based on
[Keep a Changelog](https://keepachangelog.com/en/1.1.0/), and this project
adheres to [Semantic Versioning](https://semver.org/spec/v2.0.0.html).
EOF
    for version in ${versions[@]+"${versions[@]}"}; do
      printf '\n'
      cat "${_work}/section/${version}"
    done
    printf '\n'
    for version in ${versions[@]+"${versions[@]}"}; do
      if [[ -f "${_work}/ref/${version}" ]]; then
        cat "${_work}/ref/${version}"
      fi
    done
  } | dybatpho::file_write_atomic "${_archive}"
}

# @description Rewrite the main changelog without the archived sections and
#   their link references, with a fresh archive index in its preamble.
# @arg $1 path Main changelog
# @arg $2 string Space-separated versions to drop
# @arg $3 path File holding the index block, empty when there is no archive
# @internal
function __dybatpho_changelog_render_main {
  local _changelog _drop _index
  dybatpho::expect_args _changelog _drop _index -- "$@"
  awk -v drop=" ${_drop} " -v index_file="${_index}" \
    -v begin="${ARCHIVE_BEGIN}" -v end="${ARCHIVE_END}" '
    function dropped(v) { return index(drop, " " v " ") > 0 }
    # The old index and the blank line after it go; a fresh one is written
    # before the first section, so a rerun puts it back in the same place.
    $0 == begin { in_index = 1; next }
    in_index { if ($0 == end) { in_index = 0; after_index = 1 }; next }
    after_index { after_index = 0; if ($0 ~ /^[[:space:]]*$/) next }
    /^## \[/ {
      if (!indexed) {
        indexed = 1
        if (index_file != "") {
          while ((getline line < index_file) > 0) print line
          close(index_file)
          print ""
        }
      }
      version = $0
      sub(/^## \[/, "", version); sub(/\].*$/, "", version)
      skipping = dropped(version)
      if (skipping) next
      print
      next
    }
    /^\[[^]]+\]: / {
      skipping = 0
      version = $0
      sub(/^\[/, "", version); sub(/\]: .*$/, "", version)
      if (dropped(version)) next
      print
      next
    }
    skipping { next }
    { print }
  ' "${_changelog}" | dybatpho::file_write_atomic "${_changelog}"
}

# @description Archive every section older than `--before`.
# @noargs
# @internal
function __dybatpho_changelog_archive_run {
  # shellcheck disable=SC2154 # set by the option spec of this script
  local changelog="${ARCHIVE_CHANGELOG}" before="${ARCHIVE_BEFORE}" archive_dir="${ARCHIVE_TARGET}"
  dybatpho::is file "${changelog}" || dybatpho::die "No changelog at ${changelog}"
  grep -q '^## \[Unreleased\]' "${changelog}" \
    || dybatpho::die "${changelog} has no '## [Unreleased]' section"

  local changelog_dir
  changelog_dir="$(cd "$(dirname "${changelog}")" && pwd)"
  [[ -n "${archive_dir}" ]] || archive_dir="${changelog_dir}/docs/changelog"

  local -a moved=()
  local version order versions
  versions="$(__dybatpho_changelog_versions "${changelog}")"
  while IFS= read -r version || [[ -n "${version}" ]]; do
    [[ -n "${version}" ]] || continue
    # Both sides are validated release versions, so the comparison cannot fail.
    order="$(dybatpho::semver_compare "${version}" "${before}")"
    [[ "${order}" == "-1" ]] && moved+=("${version}")
  done <<< "${versions}"

  if ((${#moved[@]} == 0)); then
    dybatpho::info "No release in ${changelog} is older than ${before}"
  else
    dybatpho::info "Archiving ${#moved[@]} release(s) older than ${before}: ${moved[*]-}"
  fi
  # shellcheck disable=SC2154 # set by the option spec of this script
  if dybatpho::is true "${DRY_RUN}"; then
    return 0
  fi

  mkdir -p "${archive_dir}"
  archive_dir="$(cd "${archive_dir}" && pwd)"
  local back name
  name="$(basename "${changelog}")"
  back="$(dybatpho::path_relative "${changelog_dir}/${name}" "${archive_dir}")"

  local work
  dybatpho::create_temp work "/" "changelog"

  # Group the moved versions by major, then merge each group into its archive:
  # the archive's own sections first, then the main file's on top of them.
  local -A majors=()
  for version in ${moved[@]+"${moved[@]}"}; do
    majors["${version%%.*}"]+="${version} "
  done
  local major archive
  for major in "${!majors[@]}"; do
    archive="${archive_dir}/CHANGELOG-${major}.x.md"
    mkdir -p "${work}/${major}"
    [[ -f "${archive}" ]] && __dybatpho_changelog_extract "${archive}" "${work}/${major}" '*'
    __dybatpho_changelog_extract "${changelog}" "${work}/${major}" "${majors[${major}]}"
    __dybatpho_changelog_render_archive "${archive}" "${major}" "${work}/${major}" "${back}"
    dybatpho::info "Wrote ${archive}"
  done

  # The index lists every archive file present, not only the ones written
  # now, so it stays complete across runs with different cut-offs.
  local index="" link listing
  local -a archives=()
  listing="$(cd "${archive_dir}" && find . -maxdepth 1 -name 'CHANGELOG-*.x.md')"
  listing="$(printf '%s\n' "${listing}" | sed 's|^\./||' | sort -t- -k2,2nr)"
  while IFS= read -r archive || [[ -n "${archive}" ]]; do
    [[ -n "${archive}" ]] && archives+=("${archive}")
  done <<< "${listing}"
  if ((${#archives[@]})); then
    index="${work}/index.md"
    {
      printf '%s\n' "${ARCHIVE_BEGIN}"
      printf 'Older releases are archived by major version:'
      local separator=" "
      for archive in ${archives[@]+"${archives[@]}"}; do
        link="$(dybatpho::path_relative "${archive_dir}/${archive}" "${changelog_dir}")"
        major="${archive#CHANGELOG-}"
        printf '%s[%s](%s)' "${separator}" "${major%.md}" "${link}"
        separator=", "
      done
      printf '.\n%s\n' "${ARCHIVE_END}"
    } > "${index}"
  fi

  __dybatpho_changelog_render_main "${changelog}" "${moved[*]-}" "${index}"
  dybatpho::info "Updated ${changelog}"
}

# @description CLI specification for this script.
# @noargs
# dyshellint disable=BSG052 # `dybatpho::generate_from_spec` adds `--help` to every spec, so the option already exists
function _spec {
  dybatpho::opts::setup \
    "Move CHANGELOG.md sections older than a version into per-major archive files" \
    ARCHIVE_ARGS action:"__dybatpho_changelog_archive_run"

  dybatpho::opts::param "Archive every release older than this version" ARCHIVE_BEFORE --before \
    required:true validate:"__dybatpho_changelog_is_release \$OPTARG"
  dybatpho::opts::param "Changelog to split" ARCHIVE_CHANGELOG --changelog \
    init:="${DYBATPHO_DIR}/CHANGELOG.md"
  dybatpho::opts::param "Directory of the archive files [default: docs/changelog next to the changelog]" \
    ARCHIVE_TARGET --archive-dir init:@empty
  dybatpho::opts::flag "Report what would move and change nothing" DRY_RUN -n --dry-run \
    on:true off:false init:="false"
}

dybatpho::generate_from_spec _spec "$@"
